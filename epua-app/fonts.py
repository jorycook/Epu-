"""Cut the two typefaces down to the characters the app shows, so they ship with the app and work offline.

usage: python3 fonts.py <fonts-src dir> <out dir> <text file> [<text file> ...]
Writes <out>/fonts/*.woff2 and <out>/fonts.css, and prints what each file holds and which characters it lacks.
Stops (exit 1) when a face lacks a Guarani letter: the app must draw every one of them in its own typefaces.

Both typefaces are under the SIL Open Font License 1.1; the licence text goes into the app's licences file.
  Nunito (the interface) comes as one variable font: its 500, 700 and 800 are made from it here.
  Andika (Guarani text) has the Reserved Font Names "Andika" and "SIL", and a subset is a Modified Version of it, so
  the subsets are renamed EpuaText, a name with neither word in it. The build writes 'EpuaText' where the screens
  say 'Andika' (the design canvas keeps loading Andika itself from Google Fonts).
Keeping the mark, mkmk and ccmp features keeps the tilde of g̃ and G̃ (g + U+0303, there is no single letter) on its
letter, and every nasal vowel drawn as the typeface means it.
"""
import html
import os
import re
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

SRC, OUT = sys.argv[1], sys.argv[2]
# family in the style sheets, weight, source file, the weight to make from a variable font (or None), file name, new family name (or None)
FACES = [
    ("Nunito", 500, "nunito/Nunito[wght].ttf", 500, "nunito-500", None),
    ("Nunito", 700, "nunito/Nunito[wght].ttf", 700, "nunito-700", None),
    ("Nunito", 800, "nunito/Nunito[wght].ttf", 800, "nunito-800", None),
    ("EpuaText", 400, "andika/Andika-Regular.ttf", None, "epuatext-400", "EpuaText"),
    ("EpuaText", 700, "andika/Andika-Bold.ttf", None, "epuatext-700", "EpuaText"),
]
RESERVED = re.compile(r"andika|\bsil\b", re.I)
# the names a renamed face must not carry a Reserved Font Name in (family, unique id, full name, PostScript name, typographic names)
NAMED = (1, 3, 4, 6, 16, 17, 18, 21, 22, 25)

# The Guarani letters (the Academy's alphabet: the nasal vowels, g̃, ñ, the puso), both cases, with the accented vowels
# and the Spanish signs: always in, whether the text of this build has them or not (the keyboards type capitals too).
COMBINING = "̃́"
GUARANI = "aãeẽiĩoõuũyỹAÃEẼIĨOÕUŨYỸgGñÑ'" + COMBINING
SPANISH = "áéíóúýüÁÉÍÓÚÝÜ¿¡«»·…–—’‘“”"

# every character that appears in the files the app is built from, plus plain ASCII
chars = set(chr(c) for c in range(0x20, 0x7F))
chars.update(GUARANI + SPANISH)
for path in sys.argv[3:]:
    text = open(path, encoding="utf-8").read()
    text = html.unescape(text)
    # characters written as \uXXXX in the screens' code
    text += "".join(chr(int(m, 16)) for m in re.findall(r"\\u([0-9a-fA-F]{4})", text))
    chars.update(text)
chars = sorted(c for c in chars if ord(c) >= 0x20 and c not in " 　﻿​  ")
codepoints = [ord(c) for c in chars]


def renamed(font, family):
    """The face under its new family name, with no Reserved Font Name left in any of its names."""
    name = font["name"]
    style = (name.getDebugName(2) or "Regular").strip()
    version = (name.getDebugName(5) or "").replace("Version ", "").strip()
    ps_style = style.replace(" ", "")
    full = family if style == "Regular" else family + " " + style
    for record in list(name.names):
        if record.nameID in NAMED:
            name.removeNames(nameID=record.nameID)
    for name_id, value in ((1, family), (2, style), (3, "%s-%s %s; a subset for the Epu'ã app" % (family, ps_style, version)), (4, full), (6, "%s-%s" % (family, ps_style))):
        name.setName(value, name_id, 3, 1, 0x409)
    left = [(r.nameID, str(r)) for r in name.names if r.nameID in NAMED and RESERVED.search(str(r))]
    if left:
        sys.exit("fonts.py: a Reserved Font Name is still in %s: %r" % (family, left))


os.makedirs(os.path.join(OUT, "fonts"), exist_ok=True)
css = ["/* Generated by fonts.py: the app's two typefaces, cut down to the characters the app shows. EpuaText is Andika, renamed (see licenses.txt). */"]
total = 0
lacking = []
for family, weight, src, instance, out_name, new_family in FACES:
    font_path = os.path.join(SRC, src)
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["ccmp", "locl", "liga", "clig", "calt", "kern", "mark", "mkmk", "rlig"]
    opts.hinting = False
    opts.desubroutinize = True
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    opts.name_languages = ["*"]
    opts.notdef_outline = True
    opts.drop_tables += ["DSIG", "Silt"]
    # the same files make the same fonts, build after build (no new timestamp): a phone keeps the ones it has
    font = TTFont(font_path, recalcTimestamp=False)
    if instance is not None:
        # one weight of the variable font, as a plain (static) font
        try:
            font = instancer.instantiateVariableFont(font, {"wght": instance}, updateFontNames=True)
        except Exception:
            font = instancer.instantiateVariableFont(font, {"wght": instance})
        font["OS/2"].usWeightClass = instance
    cmap = font.getBestCmap()
    have = [cp for cp in codepoints if cp in cmap]
    missing = [chr(cp) for cp in codepoints if cp not in cmap and cp > 0x7F]
    lacking += ["%s %d lacks %s (U+%04X)" % (family, weight, chr(cp), cp) for cp in map(ord, GUARANI) if cp not in cmap]
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=have)
    sub.subset(font)
    if new_family:
        renamed(font, new_family)
    out_path = os.path.join(OUT, "fonts", out_name + ".woff2")
    subset.save_font(font, out_path, opts)
    size = os.path.getsize(out_path)
    total += size
    css.append(
        "@font-face{font-family:'%s';font-style:normal;font-weight:%d;font-display:swap;src:url(./fonts/%s.woff2) format('woff2')}"
        % (family, weight, out_name)
    )
    print("%-14s %4d characters, %6d bytes; not in this typeface (the system font draws them): %s" % (out_name, len(have), size, "".join(missing) or "none"))
open(os.path.join(OUT, "fonts.css"), "w", encoding="utf-8").write("\n".join(css) + "\n")
print("characters in the app: %d, fonts total %d bytes" % (len(chars), total))
if lacking:
    sys.exit("fonts.py: a typeface lacks a Guarani letter, the app would draw it in another font:\n  " + "\n  ".join(lacking))
